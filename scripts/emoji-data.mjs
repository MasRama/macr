// Writes src/features/emoji/logic/data.ts from Unicode's emoji-test.txt:
// fully-qualified emoji, without skin tone variants or components.
// Usage: node scripts/emoji-data.mjs [/usr/share/unicode/emoji/emoji-test.txt]
import { readFileSync, writeFileSync } from 'node:fs';

const source = process.argv[2] ?? '/usr/share/unicode/emoji/emoji-test.txt';
const text = readFileSync(source, 'utf8');
const version = /^# Version: (.+)$/m.exec(text)?.[1] ?? '?';

const lines = [];
let group = '';
for (const line of text.split('\n')) {
    const heading = /^# group: (.+)$/.exec(line);
    if (heading) {
        group = heading[1];
        continue;
    }
    const entry = /^[0-9A-F ]+;\s*fully-qualified\s*#\s*(\S+)\s+E[\d.]+\s+(.+)$/.exec(line);
    if (!entry || group === 'Component' || entry[2].includes('skin tone')) continue;
    lines.push(`${group}\t${entry[1]}\t${entry[2]}`);
}

const out = `// Generated by scripts/emoji-data.mjs from Unicode emoji-test.txt ${version}. Do not edit.
// group, emoji and name, tab separated, one per line.

export const EMOJI_DATA = \`
${lines.join('\n').replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${')}
\`;
`;
writeFileSync(new URL('../src/features/emoji/logic/data.ts', import.meta.url), out);
console.log(`${lines.length} emoji from Unicode ${version}`);
